//! # Kite
//!
//! A declarative UI framework in the spirit of Slint: describe your UI in
//! `.ui` files, compile them to Rust at build time (or load them at
//! runtime), and run the same UI on the desktop, in the browser, or on a
//! microcontroller.
//!
//! ```text
//! // ui/hello.ui
//! export component Hello inherits Window {
//!     in-out property <int> count;
//!     VerticalLayout {
//!         padding: 16px;
//!         Text { text: "Clicked \{count} times"; }
//!         Button { text: "Click"; clicked => { count += 1; } }
//!     }
//! }
//! ```
//!
//! ```ignore
//! // build.rs
//! fn main() { kite_build::compile("ui/hello.ui"); }
//!
//! // main.rs
//! kite::include_ui!("hello");
//! use kite::prelude::*;
//!
//! fn main() -> Result<(), Box<dyn std::error::Error>> {
//!     let app = Hello::new();
//!     app.set_count(41);
//!     app.run()
//! }
//! ```
//!
//! Without the default features Kite is `no_std` + `alloc`.
#![no_std]
#![forbid(unsafe_code)]

#[cfg(feature = "std")]
extern crate std;

pub use kite_core::*;

/// Includes the Rust code generated by `kite_build::compile` for `<name>.ui`.
#[macro_export]
macro_rules! include_ui {
    ($name:literal) => {
        include!(concat!(env!("OUT_DIR"), "/", $name, ".rs"));
    };
}

/// Native desktop windows.
#[cfg(feature = "desktop")]
pub use kite_winit as desktop;

/// Runtime compilation of `.ui` sources.
#[cfg(feature = "interpreter")]
pub use kite_compiler as interpreter;

/// Offscreen rendering and simulated input.
#[cfg(feature = "headless")]
pub use kite_headless as headless;

/// Adds `.run()` to every component.
#[cfg(feature = "desktop")]
pub trait RunExt: Component {
    /// Shows the component in a window and runs the event loop until it closes.
    fn run(&self) -> Result<(), std::boxed::Box<dyn std::error::Error>> {
        kite_winit::run(self)
    }
}

#[cfg(feature = "desktop")]
impl<T: Component> RunExt for T {}

/// Loads a `.ui` file at runtime and instantiates its main component.
#[cfg(feature = "interpreter")]
pub fn load(
    path: impl AsRef<std::path::Path>,
) -> Result<ComponentInstance, kite_compiler::Diagnostics> {
    kite_compiler::compile_file(path).map(|c| c.instantiate())
}

pub mod prelude {
    #[cfg(feature = "desktop")]
    pub use crate::RunExt;
    pub use crate::{Color, Component, ComponentInstance, Value};
}
