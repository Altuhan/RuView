#!/usr/bin/env python3
"""Rasterize a TrueType font into Kite's built-in 8-bit alpha glyph atlas.

The atlas lets the no_std software renderer draw text on every target
(desktop, web, MCU) without a font engine. Glyphs are rendered once at
BASE_SIZE pixels and scaled at runtime.

Usage: python3 tools/gen_font.py /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

BASE_SIZE = 32
EXTRA = "°•…×·–—‘’“”€"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)

def main() -> None:
    src = sys.argv[1]
    out_dir = os.path.join(os.path.dirname(__file__), "..", "crates", "kite-core", "src", "font")
    font = ImageFont.truetype(src, BASE_SIZE)
    ascent, descent = font.getmetrics()
    data = bytearray()
    rows = []
    for ch in sorted(CHARS, key=ord):
        advance = font.getlength(ch)
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            data.extend(img.tobytes())
        rows.append((ord(ch), round(advance * 64), x0, y0, w, h, offset))
    with open(os.path.join(out_dir, "atlas.bin"), "wb") as f:
        f.write(bytes(data))
    with open(os.path.join(out_dir, "atlas.rs"), "w") as f:
        f.write("// @generated by tools/gen_font.py — do not edit.\n")
        f.write("// Rasterized from DejaVu Sans; see LICENSE-FONT in this directory.\n")
        f.write(f"pub const BASE_SIZE: f32 = {BASE_SIZE}.0;\n")
        f.write(f"pub const ASCENT: f32 = {ascent}.0;\n")
        f.write(f"pub const DESCENT: f32 = {descent}.0;\n")
        f.write("pub static DATA: &[u8] = include_bytes!(\"atlas.bin\");\n")
        f.write("/// (codepoint, advance*64, bearing_x, bearing_y, width, height, offset)\n")
        f.write("pub static GLYPHS: &[(u32, u16, i8, i8, u8, u8, u32)] = &[\n")
        for r in rows:
            f.write("    ({}, {}, {}, {}, {}, {}, {}),\n".format(*r))
        f.write("];\n")
    print(f"{len(rows)} glyphs, {len(data)} bytes")

if __name__ == "__main__":
    main()
